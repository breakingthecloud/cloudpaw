"""Export the trained policy (an MLP) to plain C for the ESP32: one header, no libraries, float32, static weights.

    python -m cloudpaw_rl.export_c policy.npz cloudpaw_policy.h

policy.npz holds W0, b0, W1, b1, ... (Wi shape = (out, in)) — what you save after PPO training (e.g. from the actor of
Stable-Baselines3/skrl/rsl_rl: export the actor's Linear layers). Hidden layers use tanh (ESP32-friendly), the output is
tanh too (actions in [-1, 1]). Optional `obs_mean`/`obs_std` arrays are folded into the header (observation normalization).
"""

from __future__ import annotations

import sys
from typing import List, Sequence

import numpy as np


def forward(obs: np.ndarray, weights: Sequence[np.ndarray], biases: Sequence[np.ndarray], obs_mean=None, obs_std=None) -> np.ndarray:
    """Reference forward pass (what the C code must reproduce)."""
    x = np.asarray(obs, dtype=np.float32)
    if obs_mean is not None:
        x = (x - obs_mean.astype(np.float32)) / obs_std.astype(np.float32)
    for w, b in zip(weights, biases):
        x = np.tanh(w.astype(np.float32) @ x + b.astype(np.float32))
    return x


def _array(name: str, a: np.ndarray) -> str:
    vals = ", ".join(f"{float(v):.9g}f" for v in np.asarray(a, dtype=np.float32).ravel())
    return f"static const float {name}[{a.size}] = {{{vals}}};\n"


def to_c_header(weights: List[np.ndarray], biases: List[np.ndarray], obs_mean=None, obs_std=None, name: str = "cloudpaw_policy") -> str:
    sizes = [weights[0].shape[1]] + [w.shape[0] for w in weights]
    for i, (w, b) in enumerate(zip(weights, biases)):
        if w.shape[1] != sizes[i] or b.shape != (w.shape[0],):
            raise ValueError(f"layer {i}: weight {w.shape} / bias {b.shape} do not chain with input size {sizes[i]}")
    widest = max(sizes)
    guard = name.upper() + "_H"
    out = [f"/* Generated by cloudpaw_rl.export_c. MLP {' -> '.join(map(str, sizes))}, tanh, float32. Do not edit. */\n",
           f"#ifndef {guard}\n#define {guard}\n#include <math.h>\n\n",
           f"#define {name.upper()}_N_OBS {sizes[0]}\n#define {name.upper()}_N_ACT {sizes[-1]}\n\n"]
    for i, (w, b) in enumerate(zip(weights, biases)):
        out.append(_array(f"{name}_w{i}", w))
        out.append(_array(f"{name}_b{i}", b))
    if obs_mean is not None:
        out.append(_array(f"{name}_obs_mean", obs_mean))
        out.append(_array(f"{name}_obs_std", obs_std))
    out.append(f"\n/* obs[{sizes[0]}] -> act[{sizes[-1]}] in [-1, 1]. Uses two stack buffers of {widest} floats. */\n")
    out.append(f"static inline void {name}_forward(const float *obs, float *act) {{\n")
    out.append(f"  float a[{widest}], b[{widest}];\n")
    norm = f"(obs[i] - {name}_obs_mean[i]) / {name}_obs_std[i]" if obs_mean is not None else "obs[i]"
    out.append(f"  for (int i = 0; i < {sizes[0]}; i++) a[i] = {norm};\n")
    src, dst = "a", "b"
    for i, w in enumerate(weights):
        n_out, n_in = w.shape
        target = "act" if i == len(weights) - 1 else dst
        out.append(f"  for (int o = 0; o < {n_out}; o++) {{\n"
                   f"    float s = {name}_b{i}[o];\n"
                   f"    for (int k = 0; k < {n_in}; k++) s += {name}_w{i}[o * {n_in} + k] * {src}[k];\n"
                   f"    {target}[o] = tanhf(s);\n  }}\n")
        src, dst = dst, src
    out.append("}\n\n#endif\n")
    return "".join(out)


def main(argv=None) -> int:
    argv = argv or sys.argv[1:]
    if len(argv) != 2:
        print(__doc__)
        return 2
    data = np.load(argv[0])
    n = len([k for k in data.files if k.startswith("W")])
    weights = [data[f"W{i}"] for i in range(n)]
    biases = [data[f"b{i}"] for i in range(n)]
    mean = data["obs_mean"] if "obs_mean" in data.files else None
    std = data["obs_std"] if "obs_std" in data.files else None
    open(argv[1], "w").write(to_c_header(weights, biases, mean, std))
    print(f"wrote {argv[1]}: MLP {weights[0].shape[1]} -> " + " -> ".join(str(w.shape[0]) for w in weights))
    return 0


if __name__ == "__main__":
    sys.exit(main())
